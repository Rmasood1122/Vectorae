"""Generate docs/help-center/00-index.md from the articles themselves.

    python -m scripts.help_center.build_index           # (re)write the index
    python -m scripts.help_center.build_index --check   # exit 1 if stale

One entry per article: id, title (linked) and a one-line scope -- the leading
sentences (at least ~80 characters) of the article's opening paragraph.
Nothing is typed by hand, so the index cannot drift from the articles;
tests/help_center/test_corpus.py runs the --check comparison on every CI run.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from app.services import help_center  # noqa: E402

INDEX_NAME = "00-index.md"


# A scope shorter than this ("Vectorae has an Android app.") says too little,
# so the next sentence is added until the line is at least this long.
MIN_SCOPE_CHARS = 80


def scope_line(paragraph: str) -> str:
    """Leading sentences of the opening paragraph, on one line."""
    text = " ".join((paragraph or "").split())
    # A sentence ends at ., ! or ? followed by a space and a capital letter.
    ends = [m.start() for m in re.finditer(r"(?<=[.!?])\s+(?=[A-Z])", text)]
    for end in ends:
        if end >= MIN_SCOPE_CHARS:
            return text[:end]
    return text


def render_index(directory: Path | None = None) -> str:
    directory = directory or help_center.help_center_dir()
    corpus = help_center.load_corpus(directory)
    lines = [
        "---",
        "id: index",
        "title: Help center index",
        "owner: help-center",
        "---",
        "",
        "# Help center index",
        "",
        "Every help-center article, with its id and what it covers. Generated by",
        "`python -m scripts.help_center.build_index` from each article's front",
        "matter and opening paragraph; do not edit by hand.",
        "",
    ]
    for article in corpus.articles:
        number = article.filename.split("-", 1)[0]
        scope = scope_line(article.intro.split("\n\n")[0])
        lines.append(f"- **{number}** `{article.id}` -- "
                     f"[{article.title}]({article.filename}): {scope}")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    path = help_center.help_center_dir() / INDEX_NAME
    rendered = render_index()
    if "--check" in argv:
        current = path.read_text(encoding="utf-8") if path.is_file() else ""
        if current != rendered:
            print(f"{path} is stale -- run: python -m scripts.help_center.build_index")
            return 1
        print(f"{path} is up to date")
        return 0
    path.write_text(rendered, encoding="utf-8")
    print(f"wrote {path} ({len(rendered.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
