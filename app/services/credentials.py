_BY_PROVIDER = {spec.provider: spec for spec in CATALOGUE}


def spec_for(provider: str) -> ProviderSpec | None:
    return _BY_PROVIDER.get(provider)


def get_secret(db: Session, provider: str, key: str,
               user_id: uuid.UUID | str | None = None) -> str | None:
    """The user's own credential, else the deployment's, else None."""
    if user_id is not None:
        value = TokenStore.get(db, user_id=user_id, provider=provider, key=key)
        if value:
            return value
    return TokenStore.get(db, user_id=None, provider=provider, key=key) or None


def require_secret(db: Session, provider: str, key: str,
                   user_id: uuid.UUID | str | None = None) -> str:
    value = get_secret(db, provider, key, user_id=user_id)
    if not value:
        raise IntegrationNotConfigured(provider, key)
    return value


def is_configured(db: Session, provider: str,
                  user_id: uuid.UUID | str | None = None) -> bool:
    """True when EVERY key the catalogue lists for `provider` resolves."""
    spec = spec_for(provider)
    keys = spec.keys if spec else ()
    return bool(keys) and all(get_secret(db, provider, k, user_id=user_id)
                              for k in keys)


def set_system_secret(db: Session, provider: str, key: str, value: str) -> None:
    TokenStore.set(db, user_id=None, provider=provider, key=key, value=value)


def delete_system_secret(db: Session, provider: str, key: str | None = None) -> int:
    return TokenStore.delete(db, user_id=None, provider=provider, key=key)


def system_status(db: Session) -> list[dict]:
    """Catalogue + which keys are set. Values are never included."""
    out = []
    for spec in CATALOGUE:
        present = set(TokenStore.keys(db, user_id=None, provider=spec.provider))
        out.append({
            "provider": spec.provider,
            "label": spec.label,
            "purpose": spec.purpose,
            "scope": spec.scope,
            "keys": ([{"key": k, "is_set": k in present, "optional": False}
                      for k in spec.keys]
                     + [{"key": k, "is_set": k in present, "optional": True}
                        for k in spec.optional]),
            "configured": all(k in present for k in spec.keys),
        })
    return out
