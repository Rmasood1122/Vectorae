"""Where every third-party credential added by the feature expansion is read from.

TWO SCOPES, ONE STORE
Every secret lives in `integration_tokens`, Fernet-encrypted, written only by
app/integrations/token_store.py::TokenStore. That is a hard requirement for
everything added after M9, and it is why none of the providers below has an
environment variable: a key in the environment is a key in every process
listing, every crash dump and every `docker inspect`.

  user scope    user_id = <the user>. OAuth grants (Slack, HubSpot,
                Salesforce), a user's own LinkedIn account id, their own
                overriding API key. Belongs to one account, deleted with it.
  system scope  user_id = NULL. Deployment-wide API keys the operator pays
                for (OpenAI for the consensus engine, NewsAPI, Vapi,
                ElevenLabs, MXToolbox, Mailreach) and the OAuth *app*
                credentials (client id/secret) every user's grant is minted
                against. Set from the admin panel (/admin/integrations).

`get_secret` tries the user's own credential first and falls back to the
system one, so an agency that brings its own NewsAPI key uses it, and every
other account rides on the deployment's.

NOTHING HERE EVER RETURNS A SECRET TO AN HTTP CLIENT. `status()` reports which
keys are SET, never their values -- the admin page renders a checkmark, not a
masked string, because a masked string still leaks length and prefix.
"""

from __future__ import annotations

import uuid
