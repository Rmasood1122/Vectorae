from sqlalchemy.orm import Session

from app.core.exceptions import ClientHunterError
from app.integrations.token_store import TokenStore


class IntegrationNotConfigured(ClientHunterError):
    """A feature needs a credential nobody has set.

    Callers turn this into a soft outcome (the brief says "no news found",
    the channel reports "not connected") rather than a 500: an unconfigured
    optional integration is a deployment state, not an error.
    """

    def __init__(self, provider: str, key: str):
        self.provider = provider
        self.key = key
        super().__init__(
            f"{provider} is not configured ({key} is not set) -- an admin can "
            f"set it under Admin > Integrations"
        )


@dataclass(frozen=True)
class ProviderSpec:
    provider: str
    label: str
    keys: tuple[str, ...]
    purpose: str
    # "system": only the admin sets it. "user": only a user connects it (an
    # OAuth grant). "both": a system default a user may override.
    scope: str
    # Keys the admin MAY set that `configured` does not require (e.g. the
    # Unipile account used to READ LinkedIn posts when a user has not
    # connected their own).
    optional: tuple[str, ...] = ()


