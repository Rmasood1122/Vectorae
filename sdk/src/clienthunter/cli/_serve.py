def _check_docker() -> bool:
    """Return True if Docker is installed and the daemon is running."""
    if shutil.which("docker") is None:
        return False
    try:
        result = subprocess.run(
            ["docker", "info"],
            capture_output=True, timeout=10
        )
        return result.returncode == 0
    except (subprocess.TimeoutExpired, FileNotFoundError, OSError):
        return False


def _check_compose(compose_file: Path) -> bool:
    """Return True if docker compose v2 is available."""
    try:
        result = subprocess.run(
            ["docker", "compose", "--file", str(compose_file), "ps"],
            capture_output=True, timeout=10
        )
        return result.returncode == 0
    except (subprocess.TimeoutExpired, FileNotFoundError, OSError):
        return False


def _find_compose_file() -> Path | None:
    """Look for docker-compose.yml in CWD first, then bundled location."""
    cwd_compose = Path.cwd() / "docker-compose.yml"
    if cwd_compose.exists():
        return cwd_compose
    if _BUNDLED_COMPOSE.exists():
        return _BUNDLED_COMPOSE
    return None


def _write_compose_template() -> Path:
    """Write the bundled compose template to ~/.clienthunter/serve/."""
    _SERVE_DIR.mkdir(parents=True, exist_ok=True)
    _BUNDLED_COMPOSE.write_text(_COMPOSE_TEMPLATE, encoding="utf-8")
    return _BUNDLED_COMPOSE


def _env_file_for(compose_file: Path) -> Path:
    return compose_file.parent / ".env"


def _generate_env(env_path: Path) -> None:
    """Prompt for required secrets, generate strong defaults, write .env."""
    console.print("\n[bold]Configure secrets[/bold]")
    console.print("[muted]Required secrets are prompted; others get safe generated defaults.[/muted]\n")

    anthropic_key = Prompt.ask(
        "[bold]ANTHROPIC_API_KEY[/bold] [red](required)[/red]",
        password=True,
    )
    if not anthropic_key.strip():
        err_console.print("[error]ANTHROPIC_API_KEY is required — the pipeline cannot run without it.[/error]")
        raise typer.Exit(1)

    apollo_key = Prompt.ask("APOLLO_API_KEY (leave blank to skip)", default="", password=True)
    hunter_key = Prompt.ask("HUNTER_API_KEY (leave blank to skip)", default="", password=True)

    wa_phone = Prompt.ask("WHATSAPP_PHONE_NUMBER_ID (leave blank to skip)", default="")
    wa_token = ""
    wa_verify = ""
    if wa_phone:
        wa_token = Prompt.ask("WHATSAPP_ACCESS_TOKEN", password=True)
        wa_verify = secrets.token_hex(16)

    calendly_secret = Prompt.ask("CALENDLY_WEBHOOK_SECRET (leave blank to skip)", default="", password=True)
    gmail_id = Prompt.ask("GMAIL_CLIENT_ID (leave blank to skip)", default="")
    gmail_secret = ""
    if gmail_id:
        gmail_secret = Prompt.ask("GMAIL_CLIENT_SECRET", password=True)

    postgres_pw = secrets.token_urlsafe(24)
    secret_key = secrets.token_hex(32)

    env_content = _ENV_TEMPLATE.format(
        POSTGRES_PASSWORD=postgres_pw,
        SECRET_KEY=secret_key,
        ANTHROPIC_API_KEY=anthropic_key,
        APOLLO_API_KEY=apollo_key or "not_configured",
        HUNTER_API_KEY=hunter_key or "not_configured",
        WHATSAPP_PHONE_NUMBER_ID=wa_phone or "not_configured",
        WHATSAPP_ACCESS_TOKEN=wa_token or "not_configured",
        WHATSAPP_VERIFY_TOKEN=wa_verify or secrets.token_hex(16),
        CALENDLY_WEBHOOK_SECRET=calendly_secret or secrets.token_hex(16),
        GMAIL_CLIENT_ID=gmail_id or "not_configured",
        GMAIL_CLIENT_SECRET=gmail_secret or "not_configured",
    )

    env_path.write_text(env_content, encoding="utf-8")
    os.chmod(env_path, 0o600)
    console.print(f"[success]✓ .env written to {env_path} (mode 0600)[/success]")


def _wait_for_health(api_url: str = "http://localhost:8000") -> bool:
    """Poll /health until the backend responds or timeout."""
    import urllib.request
    deadline = time.time() + _HEALTH_TIMEOUT
    while time.time() < deadline:
        try:
            urllib.request.urlopen(f"{api_url}/health", timeout=3)
            return True
        except Exception:
            time.sleep(_HEALTH_INTERVAL)
    return False


def _run_compose(compose_file: Path, *args: str) -> int:
    """Run `docker compose --file <file> <args>` and stream output."""
    cmd = ["docker", "compose", "--file", str(compose_file), *args]
    console.print(f"[muted]$ {' '.join(cmd)}[/muted]\n")
    proc = subprocess.run(cmd)
    return proc.returncode


