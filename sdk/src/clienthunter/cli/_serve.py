@serve_app.callback(invoke_without_command=True)
def serve(
    ctx: typer.Context,
    detach: bool = typer.Option(False, "--detach", "-d",
                                help="Run containers in the background."),
) -> None:
    """Start the Vectorae backend stack on this machine via Docker Compose.

    \b
    ⚠  Self-hosted mode: campaigns run only while THIS machine is on.
       For 24/7 operation, deploy the compose stack to a cloud server.
       See: https://docs.clienthunter.ai/deploy
    """
    if ctx.invoked_subcommand is not None:
        return  # a subcommand (stop / logs) was invoked

    console.rule("[bold]Vectorae[/bold] — Self-Host Setup")

    # --- Docker check ---
    with console.status("[info]Checking Docker…[/info]"):
        docker_ok = _check_docker()

    if not docker_ok:
        err_console.print(
            "[error]✗ Docker is not installed or not running.[/error]\n\n"
            "Install Docker Desktop (Mac/Windows) or Docker Engine (Linux):\n"
            "  https://docs.docker.com/get-docker/\n\n"
            "After installing, ensure the Docker daemon is running, then retry.\n\n"
            "[muted]Note: `clienthunter serve` requires Docker — it does not install "
            "FastAPI, Celery, or other server dependencies inside Python.  "
            "All server logic runs in Docker containers.[/muted]"
        )
        raise typer.Exit(1)

    console.print("[success]✓ Docker is running.[/success]")

    # --- Find or create compose file ---
    compose_file = _find_compose_file()
    if compose_file is None:
        console.print(
            f"\n[muted]No docker-compose.yml found in {Path.cwd()}.[/muted]\n"
            f"Writing a ready-to-use template to {_BUNDLED_COMPOSE}…"
        )
        compose_file = _write_compose_template()
        console.print(f"[success]✓ Template written.[/success]")
        console.print(
            f"[warning]Note:[/warning] The template uses [bold]build: .[/bold] — "
            f"run from the repo root so Docker can build the images."
        )
    else:
        console.print(f"[success]✓ Using compose file:[/success] {compose_file}")

    # --- Generate .env if missing ---
    env_path = _env_file_for(compose_file)
    if env_path.exists():
        if not Confirm.ask(f"\n.env already exists at {env_path}. Regenerate?", default=False):
            console.print("[muted]Using existing .env.[/muted]")
        else:
            _generate_env(env_path)
    else:
        _generate_env(env_path)

    # --- Start stack ---
    console.print("\n[info]Starting containers…[/info] (first run may take a few minutes to build)")
    up_args = ["up", "--build"]
    if detach:
        up_args.append("-d")

    rc = _run_compose(compose_file, *up_args)
    if rc != 0 and not detach:
        raise typer.Exit(rc)

    if detach:
        # Wait for health
        console.print("\n[info]Waiting for backend to be ready…[/info]")
        if _wait_for_health():
            console.print("\n[success]✓ Stack is up![/success]")
            _print_urls()
        else:
            err_console.print(
                "[warning]⚠ Backend did not become healthy within "
                f"{_HEALTH_TIMEOUT}s.[/warning]\n"
                "Check logs: [bold]clienthunter serve logs[/bold]"
            )
            raise typer.Exit(1)


@serve_app.command("stop")
def serve_stop() -> None:
    """Stop all running Vectorae containers."""
    compose_file = _find_compose_file()
    if compose_file is None:
        err_console.print("[error]No docker-compose.yml found. Run from the repo root or after `clienthunter serve`.[/error]")
        raise typer.Exit(1)
    rc = _run_compose(compose_file, "down")
    if rc == 0:
        console.print("[success]✓ Stack stopped.[/success]")
    raise typer.Exit(rc)


@serve_app.command("logs")
def serve_logs(
    service: Optional[str] = typer.Argument(None, help="Service name (backend/worker/beat/db/redis). Omit for all."),
    follow: bool = typer.Option(True, "--follow/--no-follow", "-f/-F"),
    tail: int = typer.Option(50, "--tail", "-n", help="Lines of log history."),
) -> None:
    """Tail logs from one or all containers."""
    compose_file = _find_compose_file()
    if compose_file is None:
        err_console.print("[error]No docker-compose.yml found.[/error]")
        raise typer.Exit(1)

    args = ["logs", f"--tail={tail}"]
    if follow:
        args.append("-f")
    if service:
        args.append(service)

    rc = _run_compose(compose_file, *args)
    raise typer.Exit(rc)


def _print_urls() -> None:
    console.print()
    console.print("  [bold]Backend API:[/bold]  http://localhost:8000")
    console.print("  [bold]API Docs:[/bold]    http://localhost:8000/docs")
    console.print("  [bold]Frontend:[/bold]    http://localhost:3000")
    console.print()
    console.print("Connect the SDK: [bold]clienthunter init[/bold]  (use http://localhost:8000 as API URL)")
    console.print("Stop the stack:  [bold]clienthunter serve stop[/bold]")
    console.print()
    console.print(
        "[warning]⚠  Campaigns run only while this machine is on.[/warning]\n"
        "   For 24/7 operation: [link=https://docs.clienthunter.ai/deploy]https://docs.clienthunter.ai/deploy[/link]"
    )
